-- Trigger for updated_at
CREATE OR REPLACE FUNCTION update_agent_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_agent_state_updated_at
  BEFORE UPDATE ON ai_agent_state
  FOR EACH ROW EXECUTE FUNCTION update_agent_updated_at();

CREATE TRIGGER update_agent_memory_updated_at
  BEFORE UPDATE ON ai_agent_memory
  FOR EACH ROW EXECUTE FUNCTION update_agent_updated_at();

CREATE TRIGGER update_agent_tasks_updated_at
  BEFORE UPDATE ON ai_agent_tasks
  FOR EACH ROW EXECUTE FUNCTION update_agent_updated_at();

CREATE TRIGGER update_agent_alerts_updated_at
  BEFORE UPDATE ON ai_agent_alerts
  FOR EACH ROW EXECUTE FUNCTION update_agent_updated_at();